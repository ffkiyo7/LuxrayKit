import { execFile } from 'node:child_process';
import os from 'node:os';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

const baseBranch = process.env.POKEDB_REFRESH_BASE_BRANCH ?? 'main';
const refreshBranch = process.env.POKEDB_REFRESH_BRANCH ?? 'automation/pokedb-environment-refresh';
const commitMessage = 'data: refresh PokeDB environment snapshot';
const prTitle = 'data: refresh PokeDB environment snapshot';
const generatedSnapshotPaths = [
  'src/data/external/pokedb/current_environment_snapshot.json',
  'public/data/pokedb/reg-ma-environment.json',
];

const command = (name) => (process.platform === 'win32' && name === 'npm' ? 'npm.cmd' : name);

function printable(commandName, args) {
  return [commandName, ...args].join(' ');
}

async function run(commandName, args, options = {}) {
  console.log(`$ ${printable(commandName, args)}`);
  try {
    return await execFileAsync(command(commandName), args, {
      cwd: ROOT,
      windowsHide: true,
      maxBuffer: 16 * 1024 * 1024,
      ...options,
    });
  } catch (error) {
    if (error.stdout) process.stdout.write(error.stdout);
    if (error.stderr) process.stderr.write(error.stderr);
    throw error;
  }
}

async function capture(commandName, args, options = {}) {
  const { stdout } = await run(commandName, args, options);
  return stdout.trim();
}

async function commandExists(commandName, args = ['--version']) {
  try {
    await execFileAsync(command(commandName), args, {
      cwd: ROOT,
      windowsHide: true,
      maxBuffer: 1024 * 1024,
    });
    return true;
  } catch {
    return false;
  }
}

async function ensureRequiredCommands() {
  const missing = [];
  if (!(await commandExists('git'))) missing.push('git');
  if (!(await commandExists('gh'))) missing.push('gh');
  if (!(await commandExists('npm', ['--version']))) missing.push('npm');
  if (missing.length > 0) {
    throw new Error(`Missing required command(s): ${missing.join(', ')}`);
  }
}

function prBody() {
  return [
    'Generated by the LuxrayKit VPS PokeDB environment refresher.',
    '',
    '- Runs the existing `npm run data:pokedb:environment` parser and audit path.',
    '- Commits only the generated environment snapshot files.',
    '- Leaves the production Cloudflare Worker cron / Durable Object behavior unchanged.',
    '- CI will validate tests, build output, and the Worker dry-run before merge.',
    '',
    `Refresher host: \`${os.hostname()}\``,
    `Generated at: \`${new Date().toISOString()}\``,
  ].join('\n');
}

async function main() {
  await ensureRequiredCommands();

  await run('git', ['fetch', 'origin', baseBranch]);
  await run('git', ['switch', '-C', refreshBranch, `origin/${baseBranch}`]);

  await run('npm', ['run', 'data:pokedb:environment']);

  const changedGeneratedFiles = (
    await capture('git', ['diff', '--name-only', '--', ...generatedSnapshotPaths])
  )
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);

  if (changedGeneratedFiles.length === 0) {
    console.log('PokeDB generated snapshots already match remote data. No PR update needed.');
    return;
  }

  await run('git', ['add', '--', ...generatedSnapshotPaths]);
  const stagedFiles = (await capture('git', ['diff', '--cached', '--name-only']))
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);

  const unexpectedFiles = stagedFiles.filter((file) => !generatedSnapshotPaths.includes(file));
  if (unexpectedFiles.length > 0) {
    throw new Error(`Refusing to commit unexpected file(s): ${unexpectedFiles.join(', ')}`);
  }

  await run('git', ['commit', '-m', commitMessage]);
  await run('git', ['push', '--force-with-lease', 'origin', refreshBranch]);

  const existingPrNumber = await capture('gh', [
    'pr',
    'list',
    '--base',
    baseBranch,
    '--head',
    refreshBranch,
    '--state',
    'open',
    '--json',
    'number',
    '--jq',
    '.[0].number // ""',
  ]);

  if (existingPrNumber) {
    await run('gh', ['pr', 'edit', existingPrNumber, '--title', prTitle, '--body', prBody()]);
    console.log(`Updated PR #${existingPrNumber}.`);
    return;
  }

  await run('gh', [
    'pr',
    'create',
    '--base',
    baseBranch,
    '--head',
    refreshBranch,
    '--title',
    prTitle,
    '--body',
    prBody(),
  ]);
}

await main();
