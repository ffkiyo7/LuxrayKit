import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parsePokeDbSpeedTable } from './pokedb-speed-tier-utils.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BASE_URL = process.env.POKEDB_BASE_URL ?? 'https://champs.pokedb.tokyo';
const OUTPUT_PATH = resolve(ROOT, 'src/data/speedTiers.ts');
const USER_AGENT = 'LuxrayKitSpeedTierSnapshot/0.1 (+https://luxraykit.com)';
const checkOnly = process.argv.includes('--check');

const fetchHtml = async (url) => {
  const response = await fetch(url, {
    cache: 'no-store',
    headers: { accept: 'text/html', 'cache-control': 'no-cache', pragma: 'no-cache', 'user-agent': USER_AGENT },
  });
  if (!response.ok) throw new Error(`${url} returned ${response.status}`);
  return response.text();
};

const seasonFromArg = () => {
  const value = process.argv.find((argument) => argument.startsWith('--season='))?.split('=')[1];
  if (!value) return undefined;
  const season = Number(value);
  if (!Number.isInteger(season) || season <= 0) throw new Error(`Invalid season: ${value}`);
  return season;
};

const detectLatestSeason = async () => {
  const html = await fetchHtml(`${BASE_URL.replace(/\/$/, '')}/pokemon/list?rule=0`);
  const seasons = [...html.matchAll(/<option\s+value="(\d+)"/g)].map((match) => Number(match[1]));
  const latest = Math.max(...seasons.filter((season) => Number.isInteger(season) && season > 0));
  if (!Number.isFinite(latest)) throw new Error('PokeDB did not expose a valid season');
  return latest;
};

const season = seasonFromArg() ?? (await detectLatestSeason());
const snapshots = await Promise.all(
  [0, 1].map(async (rule) => {
    const sourceUrl = `${BASE_URL.replace(/\/$/, '')}/speed?season=${season}&rule=${rule}`;
    const snapshot = parsePokeDbSpeedTable(await fetchHtml(sourceUrl), rule);
    if (snapshot.tiers.length === 0) throw new Error(`No speed tiers parsed from ${sourceUrl}`);
    console.log(`Parsed rule ${rule}: ${snapshot.tiers.length} tiers.`);
    return snapshot;
  }),
);

const output = `// Generated by scripts/generate-pokedb-speed-tiers.mjs. Do not edit by hand.\n` +
  `export type SpeedTierSnapshot = {\n` +
  `  rule: 0 | 1;\n` +
  `  tiers: Array<{\n` +
  `    speed: number;\n` +
  `    label: string;\n` +
  `    count: number;\n` +
  `    code: string;\n` +
  `    color: string;\n` +
  `    pokemon: Array<{ dexNo: number; form: string; japaneseName: string }>;\n` +
  `  }>;\n` +
  `};\n\n` +
  `export const speedTierSeason = ${season};\n` +
  `export const speedTierSnapshots: SpeedTierSnapshot[] = ${JSON.stringify(snapshots, null, 2)};\n`;

const current = await readFile(OUTPUT_PATH, 'utf8').catch(() => '');
if (current === output) {
  console.log(`Speed tier snapshot is current for M-${season}.`);
} else if (checkOnly) {
  console.error(`Speed tier snapshot is stale for M-${season}. Run npm run data:pokedb:speed.`);
  process.exitCode = 1;
} else {
  await writeFile(OUTPUT_PATH, output, 'utf8');
  console.log(`Wrote ${OUTPUT_PATH}.`);
}
