/**
 * Emits `src/data/seed/regMA/move-ids.ts` — nothing but the move id list.
 *
 * `move-catalog.ts` is 362 KB (55 KB gzip) because every move carries Chinese text and its
 * `learnableByPokemonIds` list. The environment audit (`src/data/environment.ts`) only ever
 * needed the ids, and importing the whole catalog for them pinned the `regma-moves` chunk to
 * the environment first paint. This derives the id array at maintenance time instead.
 *
 * Purely local: the catalog is bundled with esbuild and imported, exactly like
 * `scripts/precache-manifest.mjs`. No network access.
 *
 *   node scripts/generate-move-ids.mjs           # rewrite the file
 *   node scripts/generate-move-ids.mjs --check   # CI gate: fail if it drifted
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MOVE_CATALOG_PATH = resolve(ROOT, 'src/data/seed/regMA/move-catalog.ts');
const OUTPUT_PATH = resolve(ROOT, 'src/data/seed/regMA/move-ids.ts');
const BUNDLE_PATH = resolve(ROOT, '.npm-cache/move-ids-catalog.mjs');

async function loadMoveCatalog() {
  await mkdir(dirname(BUNDLE_PATH), { recursive: true });
  await esbuild.build({
    entryPoints: [MOVE_CATALOG_PATH],
    outfile: BUNDLE_PATH,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    logLevel: 'silent',
  });
  const module = await import(`${pathToFileURL(BUNDLE_PATH).href}?t=${Date.now()}`);
  return module.championsMoves;
}

/** Catalog order is the contract: the audit compares id sets, but a stable order keeps diffs readable. */
export function renderMoveIdsModule(moves) {
  const ids = moves.map((move) => move.id);
  const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index);
  if (duplicates.length > 0) {
    throw new Error(`move-catalog.ts has duplicate move ids: ${[...new Set(duplicates)].join(', ')}`);
  }

  return [
    '// Auto-generated by scripts/generate-move-ids.mjs from move-catalog.ts. Do not edit by hand.',
    '//',
    '// The id list alone, so the environment audit can validate move references without pulling',
    '// the 362 KB move catalog into the first paint. `npm run data:regma:move-ids:check` (run by',
    "// src/lib/dataAudit.test.ts) fails if this drifts from the catalog.",
    '',
    'export const moveIds: string[] = [',
    ...ids.map((id) => `  '${id}',`),
    '];',
    '',
  ].join('\n');
}

async function main() {
  const check = process.argv.includes('--check');
  const moves = await loadMoveCatalog();
  const rendered = renderMoveIdsModule(moves);
  const relativeOutput = relative(ROOT, OUTPUT_PATH);

  if (check) {
    const existing = await readFile(OUTPUT_PATH, 'utf8').catch(() => null);
    if (existing !== rendered) {
      console.error(`${relativeOutput} is out of date. Run: npm run data:regma:move-ids`);
      process.exitCode = 1;
      return;
    }
    console.log(`${relativeOutput} is up to date (${moves.length} moves).`);
    return;
  }

  await writeFile(OUTPUT_PATH, rendered);
  console.log(`Wrote ${relativeOutput} (${moves.length} moves).`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
